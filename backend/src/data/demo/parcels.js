// Build a small rectangular polygon around a center point (GeoJSON [lng,lat]).
function rectPolygon(lat, lng, halfDeg) {
  return {
    type: 'Polygon',
    coordinates: [
      [
        [lng - halfDeg, lat - halfDeg],
        [lng - halfDeg, lat + halfDeg],
        [lng + halfDeg, lat + halfDeg],
        [lng + halfDeg, lat - halfDeg],
        [lng - halfDeg, lat - halfDeg],
      ],
    ],
  }
}

