export function getParcelById(id: string): Parcel | undefined {
  return parcels.find(p => p.id === id)
}

export function getParcelByULPIN(ulpin: string): Parcel | undefined {
  return parcels.find(p => p.ulpin === ulpin)
}

export function searchParcels(query: string): Parcel[] {
  const q = query.toLowerCase()
  return parcels.filter(p =>
    p.ulpin.toLowerCase().includes(q) ||
    p.surveyNumber.toLowerCase().includes(q) ||
    p.ownerName.toLowerCase().includes(q) ||
    p.village.toLowerCase().includes(q) ||
    p.district.toLowerCase().includes(q) ||
    p.village.toLowerCase().includes(q)
  )
}

export function getParcelsByDistrict(district: string): Parcel[] {
  return parcels.filter(p => p.district.toLowerCase() === district.toLowerCase())
}
